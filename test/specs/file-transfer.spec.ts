import { expect } from '@wdio/globals';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import UploadPage from '../pageobjects/upload.page.js';

/**
 * File upload.
 *
 * Fixtures are generated into a temp directory rather than committed. A
 * committed binary is one more thing to keep in sync, and generating it proves
 * the test controls its own preconditions — the same reason test data is
 * generated per run rather than maintained by hand.
 */
describe('File upload', () => {
    let workDir: string;

    before(() => {
        workDir = mkdtempSync(join(tmpdir(), 'wdio-upload-'));
    });

    after(() => {
        rmSync(workDir, { recursive: true, force: true });
    });

    beforeEach(async () => {
        await UploadPage.open();
    });

    it('uploads a text file and echoes its name back', async () => {
        const file = join(workDir, 'report.txt');
        writeFileSync(file, 'generated by the test run', 'utf8');

        await UploadPage.uploadFile(file);

        await expect(UploadPage.heading).toHaveText('File Uploaded!');
        expect(await UploadPage.uploadedFileName()).toBe('report.txt');
    });

    it('preserves a name containing spaces and unicode', async () => {
        // Encoding and escaping bugs hide here: a name that survives ASCII
        // often breaks once it carries spaces or non-Latin characters.
        const file = join(workDir, 'звіт тестування.txt');
        writeFileSync(file, 'unicode filename', 'utf8');

        await UploadPage.uploadFile(file);

        expect(await UploadPage.uploadedFileName()).toBe('звіт тестування.txt');
    });

    it('uploads a larger file without truncating the name', async () => {
        const file = join(workDir, 'payload.csv');
        const rows = Array.from({ length: 5000 }, (_, i) => `${i},row-${i}`).join('\n');
        writeFileSync(file, rows, 'utf8');

        await UploadPage.uploadFile(file);

        expect(await UploadPage.uploadedFileName()).toBe('payload.csv');
    });

    it('rejects submitting with no file selected', async () => {
        await UploadPage.submitButton.click();

        // Negative case: the app must not report success for an empty submit.
        await expect(UploadPage.heading).not.toHaveText('File Uploaded!');
    });
});
